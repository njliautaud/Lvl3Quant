BINARY = LVL3_ROOT / 'rust_cache_builder' / 'target' / 'release' / _bin_name
MBO_DIR = LVL3_ROOT / 'mbo'
RESULTS_DIR = LVL3_ROOT / 'alpha_discovery' / 'results'
RESULTS_DIR.mkdir(parents=True, exist_ok=True)

# Reuse predictions from CNN passive sim
PRED_DIR = LVL3_ROOT / 'data' / 'processed' / 'cnn_sim_predictions'
SIM_OUT_DIR = LVL3_ROOT / 'data' / 'processed' / 'cnn_chase_sim_results'
SIM_OUT_DIR.mkdir(parents=True, exist_ok=True)

TICK_VALUE = 12.50

_ts = datetime.now().strftime('%Y%m%d_%H%M%S')
_log_file = str(RESULTS_DIR / f'cnn_chase_sweep_{_ts}.log')

log = logging.getLogger('cnn_chase_sweep')
log.setLevel(logging.INFO)
_fh = logging.FileHandler(_log_file, mode='w', encoding='utf-8')
