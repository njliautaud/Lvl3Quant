#!/usr/bin/env python3
"""
CNN Chase/Cancel-Replace Sweep — Test cancel-replace entries through Rust MBO Sim
=================================================================================
Uses the SAME predictions already generated by cnn_rust_sim_validation.py
but runs with --chase-entry flag (reprice to new BBO if it moves away).

This is the middle ground between passive limit (5.7% fill, profitable)
and market orders (100% fill, catastrophic). Chase mode should yield
~15-25% fill rate with potentially better per-trade P&L than market.

Usage:
    python alpha_discovery/cnn_chase_sweep.py
    python alpha_discovery/cnn_chase_sweep.py --workers 8
"""

